        self.assertFalse(papers.check_cite(bad, {e["id"]: e for e in self.scan["evidence"]})[0])
        invented = dict(ok, words="Probabilistic Sharpe Ratio Estimation")  # words not on that line
        self.assertFalse(papers.check_cite(invented, {e["id"]: e for e in self.scan["evidence"]})[0])


