class JudgeTest(unittest.TestCase):
    cands = [{"cid": "C1", "abstract": ABSTRACT}]
    profile = {"facets": [{"id": "F1"}]}

    def run_one(self, **kw):
        j = {"cid": "C1", "facet": "F1", "task": 2, "method": 2, "setting": 1,
             "quote": "we present a millisecond-level anchor-free face detector", "reason": "Model used."}
        j.update(kw)
        return papers.validate_judgments(self.cands, self.profile, [j], 4)

    def test_accepts_verbatim_quote(self):
        acc, err, below = self.run_one()
        self.assertEqual((len(acc), err, below), (1, [], []))

    def test_quote_whitespace_and_case_tolerated(self):
        acc, err, _ = self.run_one(quote="We  present a MILLISECOND-level\nanchor-free face detector")
        self.assertEqual((len(acc), err), (1, []))

    def test_paraphrase_rejected(self):
        _, err, _ = self.run_one(quote="we propose a very fast anchor free face detector")
        self.assertTrue(any("not verbatim" in e for e in err))

    def test_unknown_candidate_rejected(self):
        _, err, _ = self.run_one(cid="C99")
        self.assertTrue(any("unknown candidate" in e for e in err))

    def test_threshold(self):
        acc, _, below = self.run_one(task=2, method=0, setting=2)
        self.assertEqual((acc, below), ([], ["C1/F1"]))
        acc, _, below = self.run_one(task=1, method=1, setting=1)
        self.assertEqual(acc, [])

    def test_bad_scores(self):
        _, err, _ = self.run_one(task=3)
        self.assertTrue(err)

    def test_malformed_judgments_do_not_crash(self):
        acc, err, _ = papers.validate_judgments(self.cands, self.profile, ["x", {"cid": "C1", "facet": "F1",
                                                "task": 2, "method": 2, "setting": 2, "quote": 5, "reason": "r"}], 4)
        self.assertEqual(acc, [])
        self.assertEqual(len(err), 2)

    def test_accepted_keeps_paper_snapshot(self):
        acc, _, _ = self.run_one()
        self.assertEqual(acc[0]["paper"]["abstract"], ABSTRACT)


    def test_quote_unrelated_to_facet_warns(self):
        profile = {"facets": [{"id": "F1", "name": "Face detection", "task": "face detection", "method": "CNN",
                               "queries": ["face detector edge"]}]}
        cands = [{"cid": "C1", "abstract": ABSTRACT + " The weather was cold in Paris that winter."}]
        j = {"cid": "C1", "facet": "F1", "task": 2, "method": 2, "setting": 1, "reason": "x",
             "quote": "The weather was cold in Paris that winter"}
        warnings = []
        acc, _, _ = papers.validate_judgments(cands, profile, [j], 4, warnings)
        self.assertEqual(len(acc), 1)
        self.assertEqual(len(warnings), 1)
        warnings = []
        papers.validate_judgments(cands, profile, [dict(j, quote="anchor-free face detector, YuNet, which is")], 4, warnings)
        self.assertEqual(warnings, [])

class InterleaveTest(unittest.TestCase):
    def test_each_source_gets_a_turn(self):
        def c(cid, method, rank):
            return {"cid": cid, "abstract": "a", "facets": ["F1"], "origins": {"F1/" + method: rank}}
        cands = [c("C1", "citing", 0), c("C2", "citing", 1), c("C3", "citing", 2),
                 c("C4", "text", 1), c("C5", "text", 0), c("C6", "crossref", 0),
                 {"cid": "C7", "abstract": "", "facets": ["F1"], "origins": {"F1/text": 2}}]
        order = [p["cid"] for p in papers.interleave(cands, "F1")]
        self.assertEqual(order, ["C5", "C1", "C6", "C4", "C2", "C3"])  # no abstract -> hidden


    def test_off_topic_related_work_hidden(self):
        f = {"id": "F1", "queries": ["tree-structured Parzen estimator hyperparameter optimization"]}
        drift = {"cid": "C1", "abstract": "Symbolic regression learns hybrid dynamical systems.",
                 "title": "Hybrid systems", "facets": ["F1"], "origins": {"F1/related": 0}}
        good = {"cid": "C2", "abstract": "We extend the Parzen estimator for expensive tuning.",
                "title": "c-TPE", "facets": ["F1"], "origins": {"F1/related": 1}}
        self.assertEqual([p["cid"] for p in papers.interleave([drift, good], f)], ["C2"])

