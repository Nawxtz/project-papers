class FakeHttp:
    def __init__(self, items):
        self.items = items

    def get_json(self, url):
        return {"message": {"items": self.items}}

    def get(self, url, **kw):
        raise AssertionError("no arXiv call expected")


class VerifyByTitleTest(unittest.TestCase):
    def test_crossref_record_not_rechecked(self):
        p = {"title": "T", "doi": "10.1/x", "sources": ["crossref"]}
        self.assertEqual(papers.verify_paper(FakeHttp([]), p), ("verified", "Crossref (search record)"))

    def test_title_match_attaches_doi(self):
        p = {"title": "Pseudo-Mathematics and Financial Charlatanism", "year": 2013}
        http = FakeHttp([{"DOI": "10.1090/NOTI1105", "title": ["Pseudo-Mathematics and Financial Charlatanism"],
                          "issued": {"date-parts": [[2014]]}}])
        self.assertEqual(papers.verify_by_title(http, p), ("verified", "Crossref title match"))
        self.assertEqual(p["doi"], "10.1090/noti1105")

    def test_same_title_other_year_is_not_a_match(self):
        p = {"title": "Bootstrap Methods in Econometrics", "year": 2019}
        http = FakeHttp([{"DOI": "10.1/x", "title": ["Bootstrap Methods in Econometrics"],
                          "issued": {"date-parts": [[1995]]}}])
        self.assertEqual(papers.verify_by_title(http, p), ("no_id", ""))
        self.assertNotIn("doi", p)

    def test_unregistered_doi_falls_back_to_title(self):
        import urllib.error

        class Http404(FakeHttp):
            def get_json(self, url):
                if "/works/" in url or "datacite" in url:
                    raise urllib.error.HTTPError(url, 404, "nf", {}, None)
                return {"message": {"items": self.items}}
        p = {"title": "k-means++: the advantages of careful seeding", "year": 2007, "doi": "10.5555/1283383.1283494"}
        self.assertEqual(papers.verify_paper(Http404([]), dict(p)), ("unregistered", ""))
        hit = [{"DOI": "10.1145/1283383.1283494", "title": ["k-means++: the advantages of careful seeding"],
                "issued": {"date-parts": [[2007]]}}]
        self.assertEqual(papers.verify_paper(Http404(hit), dict(p)), ("verified", "Crossref title match"))


