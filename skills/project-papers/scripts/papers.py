def tech_hits(text):
    """Technique words in a name or sentence. Splits camelCase and snake_case first."""
    words = re.findall(r"[a-z0-9]+", re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", text or "").lower())
    return [w for w in words if w.startswith(TECH_WORDS)]


def rank_inventory(project, files, ev):
    """Weight each evidence item by kind, by where it lives (core code over scratch, tests,
    examples) and, for APIs and types, by how many source files use the name. The top items
    form the coverage list that `check` holds the profile to."""
    leaves = {}
    for e in ev:
        if e["kind"] in ("api", "symbol"):
            leaves.setdefault(re.split(r"[ .]", e["value"].split(" extends ")[0])[-1], []).append(e)
    used = {k: set() for k in leaves}
    if leaves:
        pat = re.compile(r"\b(%s)\b" % "|".join(re.escape(k) for k in sorted(leaves, key=len, reverse=True)[:400]))
        for rel, path, ext in files:
            if ext not in TEXT_EXT or ext in DOC_EXT or RE_AUX_PATH.search(rel.replace(os.sep, "/")):
                continue
            for m in pat.finditer("\n".join(read_lines(path) or [])):
                used[m.group(1)].add(rel)
    for e in ev:
        w = KIND_WEIGHT.get(e["kind"], 0.5)
        if e["kind"] in ("doc", "api", "symbol"):
            w *= 1 + 0.5 * min(len(set(tech_hits(e["value"]))), 3)
        if RE_AUX_PATH.search(e["file"].replace(os.sep, "/")):
            w *= 0.3
        if e["kind"] in ("api", "symbol"):
            n = len(used.get(re.split(r"[ .]", e["value"].split(" extends ")[0])[-1], ()))
            e["uses"] = n
            w *= 1 + math.log2(max(n, 1))
        e["weight"] = round(w, 2)


