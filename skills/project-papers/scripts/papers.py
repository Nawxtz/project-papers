def cmd_show(a):
    cands = load_json(state_path(a.project, "candidates.json"), "candidates (run search first)")["candidates"]
    profile = load_json(state_path(a.project, "profile.json"), "profile")
    shown = set()
    for f in profile["facets"]:
        if a.facet and f["id"] != a.facet:
            continue
        print("\n## %s %s (task: %s | method: %s%s)" % (f["id"], f["name"], f["task"], f["method"],
                                                        " | setting: " + f["setting"] if f["setting"] else ""))
        rows = interleave(cands, f)[:a.top]
        if not rows:
            print("(no candidates with an abstract)")
        for p in rows:
            tag = " SEED" if p["seed"] else (" graph" if p["graph"] else "")
            tag += " " + p.get("venue_class", "unknown")
            venue = " | " + p["venue"][:60] if p.get("venue") else ""
            print("%s | %s | cites %s%s | %s%s" % (p["cid"], p.get("year") or "?", p["cited_by"], tag, p["title"], venue))
            if p["cid"] in shown:
                print("   (abstract shown above)")
                continue
            shown.add(p["cid"])
            ab = p["abstract"]
            print("   " + (ab if len(ab) <= a.chars else ab[:a.chars] + " ..."))


METHOD_ORDER = ("seed", "text", "citing", "related", "crossref", "arxiv")


def off_topic(p, f):
    """True for a paper that reached this facet only through the seed graph (citing papers,
    related works) and shares fewer than 2 query or method terms with it. Graph links drift:
    in testing an Optuna seed pulled in symbolic-regression papers and a Kelly seed pulled in
    channel-coding papers, all with 0-1 shared terms, while every relevant one shared 2 or more."""
    origins = [k for k in p.get("origins", {}) if k.startswith(f["id"] + "/")]
    if not origins or any(k.rsplit("/", 1)[1] not in ("related", "citing") for k in origins):
        return False
    terms = content_terms(" ".join(f["queries"] + [f.get("method", "")]))
    return len(stem_overlap(terms, content_terms(p["title"] + " " + p["abstract"]))) < 2


def interleave(cands, f):
    """Round-robin over sources, each in its own rank order. The benchmark showed each source
    finds different relevant papers, so no single source may crowd out the others."""
    if isinstance(f, str):
        f = {"id": f, "queries": []}
    fid = f["id"]
    cands = [p for p in cands if not (f["queries"] and off_topic(p, f))]
    lists = []
    for m in METHOD_ORDER:
        key = "%s/%s" % (fid, m)
        got = [p for p in cands if p["abstract"] and key in p.get("origins", {})]
        got.sort(key=lambda p: p["origins"][key])
        lists.append(got)
    rest = [p for p in cands if p["abstract"] and fid in p["facets"]]
    lists.append(rest)
    out, seen = [], set()
    for i in range(max((len(x) for x in lists), default=0)):
        for lst in lists:
            if i < len(lst) and lst[i]["cid"] not in seen:
                seen.add(lst[i]["cid"])
                out.append(lst[i])
    return out


def validate_judgments(cands, profile, judgments, min_sum, warnings=None):
    by_cid = {p["cid"]: p for p in cands}
    facets = {f["id"] for f in profile["facets"]}
    facet_files = {f["id"]: {a["file"] for a in f.get("anchors", [])} for f in profile["facets"]}
    facet_terms = {f["id"]: content_terms(" ".join([f.get(k, "") for k in ("name", "task", "method", "setting")]
                                                   + f.get("queries", []))) for f in profile["facets"]}
    warnings = [] if warnings is None else warnings
    accepted, errors, below = [], [], []
    seen = set()
    for j in judgments:
        if not isinstance(j, dict):
            errors.append("each judgment must be a JSON object")
            continue
        cid = str(j.get("cid", ""))
        tag = "%s/%s" % (cid, j.get("facet"))
        p = by_cid.get(cid)
        if not p:
            errors.append("%s: unknown candidate id (only ids from `show` are allowed)" % tag)
            continue
        if j.get("facet") not in facets:
            errors.append("%s: unknown facet" % tag)
            continue
        if (cid, j["facet"]) in seen:
            errors.append("%s: duplicate judgment" % tag)
            continue
        seen.add((cid, j["facet"]))
        try:
            sc = {k: int(j.get(k)) for k in ("task", "method", "setting")}
        except (TypeError, ValueError):
            errors.append("%s: task/method/setting must be integers 0-2" % tag)
            continue
        if any(v not in (0, 1, 2) for v in sc.values()):
            errors.append("%s: task/method/setting must be 0, 1 or 2" % tag)
            continue
        raw_quote = str(j.get("quote", "")).strip()
        quote = norm_text(raw_quote)
        if len(quote) < 25 or len(quote.split()) < 5:
            errors.append("%s: quote must be at least 5 words copied from the abstract" % tag)
            continue
        if quote not in norm_text(p["abstract"]):
            errors.append("%s: quote is not verbatim in the abstract; copy it exactly" % tag)
            continue
        reason = str(j.get("reason", "")).strip()
        if not reason or len(reason) > 240:
            errors.append("%s: reason must be 1-240 characters" % tag)
            continue
        code = str_list(j.get("code"))
        if code and not set(code) <= facet_files.get(j["facet"], set()):
            errors.append("%s: code must list files from this facet's evidence: %s" % (
                tag, ", ".join(sorted(facet_files.get(j["facet"], set())))))
            continue
        role = str(j.get("role", "match"))
        if role not in ("match", "foundation"):
            errors.append("%s: role must be \"match\" or \"foundation\"" % tag)
            continue
        total = sc["task"] + sc["method"] + sc["setting"]
        if role == "foundation":
            # The original paper of a method or library the code uses. It explains the code
            # without being about the project's problem, so it is listed apart and needs no task match.
            if not p.get("seed"):
                errors.append("%s: role foundation is only for SEED papers (from seed_titles, seed_ids or "
                              "seed_cites)" % tag)
                continue
            if sc["method"] != 2:
                below.append(tag)
                continue
        else:
            # A venue outside the core list must fit better: one more point than the usual bar.
            need = min_sum + (1 if p.get("venue_class") == "unvetted" else 0)
            if sc["task"] == 0 or sc["method"] == 0 or total < need:
                below.append(tag)
                continue
        if facet_terms[j["facet"]] and not stem_overlap(facet_terms[j["facet"]], content_terms(raw_quote)):
            warnings.append("%s: the quote shares no term with the facet; pick a sentence that shows the match" % tag)
        # Keep a copy of the paper: a later `search` renumbers C-ids.
        paper = {k: v for k, v in p.items() if k != "origins"}
        accepted.append(dict(cid=cid, facet=j["facet"], quote=raw_quote, reason=reason, paper=paper, role=role,
                             code=code, **sc))
    return accepted, errors, below


def cmd_judge(a):
    cands = load_json(state_path(a.project, "candidates.json"), "candidates")["candidates"]
    profile = load_json(state_path(a.project, "profile.json"), "profile")
    data = load_json(a.judgments, "judgments")
    judgments = data.get("judgments") if isinstance(data, dict) else data
    if not isinstance(judgments, list):
        die('judgments file must be {"judgments": [...]}')
    warnings = []
    accepted, errors, below = validate_judgments(cands, profile, judgments, a.min_score, warnings)
    for w in warnings:
        print("WARN " + w)
    for e in errors:
        print("REJECTED " + e)
    if below:
        print("below threshold (not listed): %s" % ", ".join(below))
    print("accepted %d, invalid %d, below threshold %d" % (len(accepted), len(errors), len(below)))
    if errors:
        # Nothing is saved: a half-valid file must not reach `finalize`.
        print("accepted.json NOT written. Fix or remove the REJECTED entries and run judge again.")
        sys.exit(1)
    save_json(state_path(a.project, "accepted.json"), {"accepted": accepted})


