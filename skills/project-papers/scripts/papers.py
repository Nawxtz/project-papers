class Http:
    def __init__(self, project, offline=False):
        self.cache_dir = state_path(project, "cache")
        self.offline = offline
        mail = os.environ.get("PAPERS_MAILTO", "").strip()
        self.mailto = mail
        self.ua = "project-papers/%s (+https://github.com/Nawxtz/project-papers; %s)" % (VERSION, mail or "no-mailto")
        self.oa_key = os.environ.get("OPENALEX_API_KEY", "").strip()
        self.arxiv_lock = threading.Lock()
        self.arxiv_last = 0.0
        self.oa_lock = threading.Lock()
        self.oa_last = 0.0
        self.requests = {"openalex": 0, "arxiv": 0, "other": 0}
        self.oa_cost = 0.0  # USD, from OpenAlex's meta.cost_usd on fresh (not cached) responses
        self.local = threading.local()
        self.prune_cache()

    def prune_cache(self):
        """Delete cache files past their 24 h lifetime; they are never read again."""
        if not os.path.isdir(self.cache_dir) or self.offline:
            return
        now = time.time()
        for name in os.listdir(self.cache_dir):
            path = os.path.join(self.cache_dir, name)
            try:
                if name.endswith(".txt") and now - os.path.getmtime(path) > CACHE_TTL:
                    os.remove(path)
            except OSError:
                pass

    def _cache_file(self, url):
        return os.path.join(self.cache_dir, hashlib.sha1(url.encode()).hexdigest() + ".txt")

    def get(self, url, arxiv=False, kind="other"):
        """GET with a 24h disk cache. The OpenAlex key goes in a header, never in the URL."""
        cf = self._cache_file(url)
        self.local.fresh = False
        if os.path.exists(cf) and time.time() - os.path.getmtime(cf) < CACHE_TTL:
            with open(cf, encoding="utf-8") as f:
                return f.read()
        if self.offline:
            raise RuntimeError("offline and not cached: " + url)
        last_err = None
        for attempt in range(3):
            if kind == "openalex":
                with self.oa_lock:
                    wait = 0.2 - (time.time() - self.oa_last)
                    if wait > 0:
                        time.sleep(wait)
                    self.oa_last = time.time()
            if arxiv:
                # arXiv asks for one request every 3 seconds.
                with self.arxiv_lock:
                    wait = 3.1 - (time.time() - self.arxiv_last)
                    if wait > 0:
                        time.sleep(wait)
                    self.arxiv_last = time.time()
            try:
                self.requests[kind] = self.requests.get(kind, 0) + 1
                headers = {"User-Agent": self.ua}
                if kind == "openalex" and self.oa_key:
                    headers["Authorization"] = "Bearer " + self.oa_key
                req = urllib.request.Request(url, headers=headers)
                with urllib.request.urlopen(req, timeout=20) as r:
                    body = r.read().decode("utf-8", "replace")
                os.makedirs(self.cache_dir, exist_ok=True)
                with open(cf, "w", encoding="utf-8") as f:
                    f.write(body)
                self.local.fresh = True
                return body
            except urllib.error.HTTPError as e:
                try:
                    detail = e.read().decode("utf-8", "replace")[:200]
                except Exception:
                    detail = ""
                last_err = "HTTP %d %s" % (e.code, detail)
                if e.code == 404:
                    raise
                if e.code not in (429, 500, 502, 503, 504):
                    raise RuntimeError("%s for %s" % (last_err, url))
                if e.code == 429 and kind == "openalex" and not self.oa_key:
                    last_err += "; the free OpenAlex budget without a key is about 100 searches/day per IP. Set OPENALEX_API_KEY"
                    break  # budget exhausted: retrying only wastes time
                if kind == "openalex" and "paused" in detail.lower():
                    break  # anonymous search switched off by OpenAlex; fall back right away
                retry = e.headers.get("Retry-After")
                delay = float(retry) if retry and retry.isdigit() else 1.5 * (2 ** attempt)
                time.sleep(min(delay, 20))
            except (urllib.error.URLError, TimeoutError) as e:
                last_err = e
                time.sleep(1.5 * (2 ** attempt))
        hint = ""
        if kind == "openalex" and not self.oa_key:
            hint = " (tip: a free OPENALEX_API_KEY avoids the shared anonymous limits)"
        raise RuntimeError("request failed after retries: %s (%s)%s" % (url, last_err, hint))

    def get_json(self, url):
        return json.loads(self.get(url), strict=False)

    def openalex(self, path, params):
        if self.mailto:
            params = dict(params, mailto=self.mailto)
        url = "https://api.openalex.org/%s?%s" % (path, urllib.parse.urlencode(params))
        data = json.loads(self.get(url, kind="openalex"), strict=False)
        if getattr(self.local, "fresh", False) and isinstance(data, dict):
            with self.oa_lock:
                self.oa_cost += float((data.get("meta") or {}).get("cost_usd") or 0)
        return data

    def usage(self):
        return "network requests: %s, OpenAlex cost $%.4f (cached responses are free and not counted)" % (
            self.requests, self.oa_cost)


