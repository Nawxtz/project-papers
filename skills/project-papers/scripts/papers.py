def stem_overlap(a, b):
    """Shared terms, matching on a 5-letter prefix so "labeling"/"labels" and "bootstrap"/"bootstrapping" count."""
    pa = {w[:5] for w in a}
    return {w[:5] for w in b if w[:5] in pa}  # distinct stems: "parameter"+"parameters" count once


def rebuild_abstract(inv):
    if not inv:
        return ""
    pos = {}
    for word, idxs in inv.items():
        for i in idxs:
            pos[i] = word
    return " ".join(pos[i] for i in sorted(pos))


