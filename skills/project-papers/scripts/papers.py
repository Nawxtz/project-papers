def norm_text(s):
    """Lowercase, unify quotes/dashes, collapse whitespace. Used for verbatim checks."""
    s = (s or "").lower()
    # Typographic quotes, dashes and no-break space, keyed by code point.
    s = s.translate({0x2018: "'", 0x2019: "'", 0x201C: '"', 0x201D: '"', 0x2013: "-", 0x2014: "-", 0xA0: " "})
    return re.sub(r"\s+", " ", s).strip()


def norm_title(s):
    return re.sub(r"[^a-z0-9]+", " ", (s or "").lower()).strip()


def title_sim(a, b):
    a, b = norm_title(a), norm_title(b)
    if not a or not b:
        return 0.0
    return difflib.SequenceMatcher(None, a, b).ratio()


def clean_text(s):
    """Decode HTML entities (some records are double-escaped) and drop markup tags."""
    s = html.unescape(html.unescape(s or ""))
    s = re.sub(r"</?[A-Za-z][^>]*>", " ", s)
    return re.sub(r"\s+", " ", s).strip()


