def verify_paper(http, p):
    """Check the paper exists in a canonical registry with the same title."""
    if p.get("doi") and p.get("sources") == ["crossref"]:
        # Title and DOI both came from one Crossref record; asking Crossref again adds nothing.
        return "verified", "Crossref (search record)"
    try:
        if p.get("arxiv"):
            xml_text = http.get("https://export.arxiv.org/api/query?id_list=" + p["arxiv"], arxiv=True, kind="arxiv")
            got = parse_arxiv(xml_text)
            if got and title_sim(got[0]["title"], p["title"]) >= 0.85:
                return "verified", "arXiv"
            return "mismatch", "arXiv"
        if p.get("doi"):
            try:
                data = http.get_json("https://api.crossref.org/works/" + urllib.parse.quote(p["doi"]))
                msg = data.get("message") or {}
                titles = msg.get("title") or [""]
                if msg.get("subtitle"):
                    titles = titles + ["%s: %s" % (titles[0], msg["subtitle"][0])]
                by = "Crossref"
            except urllib.error.HTTPError as e:
                if e.code != 404:
                    raise
                # Not a Crossref DOI; many datasets, theses and preprints are registered with DataCite.
                data = http.get_json("https://api.datacite.org/dois/" + urllib.parse.quote(p["doi"]))
                titles = [t.get("title", "") for t in (data.get("data") or {}).get("attributes", {}).get("titles") or []] or [""]
                by = "DataCite"
            if max(title_sim(t, p["title"]) for t in titles) >= 0.85:
                return "verified", by
            return "mismatch", by
    except urllib.error.HTTPError as e:
        if e.code == 404:
            # Every paper here came from OpenAlex, so a 404 means bad registry metadata (ACM's
            # unregistered 10.5555 DOIs, for example), not an invented paper. Try the title.
            status, by = verify_by_title(http, p)
            return (status, by) if status == "verified" else ("unregistered", "")
        return "unchecked", str(e)
    except Exception as e:
        return "unchecked", str(e)[:80]
    return verify_by_title(http, p)


def verify_by_title(http, p):
    """No DOI or arXiv ID (repository copies, old proceedings): look for the same title in
    Crossref. A match means the paper exists in a registry; its DOI is then kept."""
    try:
        url = "https://api.crossref.org/works?" + urllib.parse.urlencode(
            {"query.bibliographic": p["title"], "rows": 5, "select": "DOI,title,subtitle,issued"})
        for it in http.get_json(url)["message"]["items"]:
            year = ((it.get("issued") or {}).get("date-parts") or [[None]])[0][0]
            if year and p.get("year") and abs(year - p["year"]) > 2:
                continue  # same title, different work (generic titles repeat)
            main = (it.get("title") or [""])[0]
            sub = (it.get("subtitle") or [""])[0]
            if max(title_sim(main, p["title"]), title_sim("%s: %s" % (main, sub), p["title"]) if sub else 0) >= 0.9:
                p["doi"] = it["DOI"].lower()
                return "verified", "Crossref title match"
        # No arXiv title search here: OpenAlex already links arXiv versions to their records,
        # and in testing 6 of 6 such lookups found nothing while costing 21 s of arXiv pacing.
    except Exception as e:
        return "unchecked", str(e)[:80]
    return "no_id", ""


def bib_key(p, used):
    last = re.sub(r"[^a-z]", "", (p["authors"][0].split()[-1] if p["authors"] else "anon").lower()) or "anon"
    word = next((w for w in norm_title(p["title"]).split() if len(w) > 3), "paper")
    key = "%s%s%s" % (last, p.get("year") or "", word)
    base, n = key, 2
    while key in used:
        key, n = "%s%s" % (base, chr(ord("a") + n - 2)), n + 1
    used.add(key)
    return key


def bib_escape(s):
    return (s or "").replace("{", "").replace("}", "").replace("&", r"\&")


def load_state(project):
    path = state_path(project, "state.json")
    if os.path.exists(path):
        return load_json(path, "state")
    return {"rejected": [], "accepted": [], "ids": {}}


def lineage(http, papers):
    """Which listed papers cite which other listed papers, from OpenAlex referenced_works.
    One request per 50 papers. Returns {cid: [cid it cites]}."""
    by_oa = {p["openalex"]: c for c, p in papers.items() if p.get("openalex")}
    by_doi = {p["doi"]: c for c, p in papers.items() if not p.get("openalex") and p.get("doi")}
    refs = {}
    for field, table in (("openalex_id", by_oa), ("doi", by_doi)):
        keys = list(table)
        for i in range(0, len(keys), 50):
            try:
                data = http.openalex("works", {"filter": "%s:%s" % (field, "|".join(keys[i:i + 50])),
                                               "per_page": 50, "select": "id,doi,referenced_works"})
            except Exception:
                return {}  # lineage is an extra; never fail finalize over it
            for w in data.get("results", []):
                oa = (w.get("id") or "").rsplit("/", 1)[-1]
                doi = (w.get("doi") or "").replace("https://doi.org/", "").lower()
                cid = by_oa.get(oa) or by_doi.get(doi)
                if cid:
                    by_oa.setdefault(oa, cid)
                    refs[cid] = [r.rsplit("/", 1)[-1] for r in w.get("referenced_works") or []]
    return {c: sorted({by_oa[r] for r in rs if r in by_oa and by_oa[r] != c}) for c, rs in refs.items()}


def cmd_finalize(a):
    accepted = load_json(state_path(a.project, "accepted.json"), "accepted.json (run judge first)")["accepted"]
    profile = load_json(state_path(a.project, "profile.json"), "profile")
    cands = {j["cid"]: j["paper"] for j in accepted}
    http = Http(a.project, offline=a.offline)
    state = load_state(a.project)
    prev = set(state["accepted"])

    uniq = {j["cid"] for j in accepted}
    with ThreadPoolExecutor(max_workers=6) as ex:  # mostly Crossref, which is slow but allows parallel calls
        results = dict(zip(uniq, ex.map(lambda c: verify_paper(http, cands[c]), uniq)))
    cites = lineage(http, {c: cands[c] for c in uniq if results[c][0] not in ("mismatch", "not_found")})

    out_md = os.path.join(a.project, a.out)
    out_bib = os.path.splitext(out_md)[0] + ".bib"
    used, bib, lines = set(), [], []
    today = dt.date.today().isoformat()
    lines += ["# Related papers", "",
              "Generated by project-papers %s on %s. Metadata comes from OpenAlex, Crossref and arXiv; every quote below "
              "is checked to appear verbatim in the paper's abstract." % (VERSION, today), ""]
    dropped = []
    new_keys = []
    codemap = []  # one entry per listed paper: which code it explains

    def render(j, n, f):
        p = cands[j["cid"]]
        status, by = results[j["cid"]]
        keys = paper_keys(p) or [p["title"]]
        new_keys.extend(keys)
        if status == "verified":
            badge = "verified via %s" % by
        elif status == "no_id":
            badge = "NOT verified: no DOI or arXiv ID to check (record from OpenAlex)"
        elif status == "unregistered":
            badge = "NOT verified: its DOI is not registered and no title match was found (record from OpenAlex)"
        else:
            badge = "NOT verified (%s)" % (by or status)
        new = "" if prev.intersection(keys) else " [new]"
        authors = ", ".join(p["authors"][:3]) + (" et al." if len(p["authors"]) > 3 else "")
        venue = (p["venue"] + " ") if p["venue"] else ""
        if p.get("venue_class") in ("established", "unvetted"):
            venue += "(%s venue) " % p["venue_class"]
        elif p.get("venue_class") in ("preprint", "thesis", "book"):
            venue += "(%s) " % p["venue_class"]
        title_md = p["title"].replace("[", "(").replace("]", ")")
        lines.append("%d. **[%s](%s)**%s  " % (n, title_md, p["url"], new))
        lines.append("   %s %s%s. Cited by %s. %s." % ((authors or "Unknown authors").rstrip(".") + ".", venue,
                                                         p.get("year") or "n.d.", p["cited_by"], badge))
        lines.append("   - Why: %s" % j["reason"])
        lines.append('   - Abstract says: "%s"' % j["quote"])
        lines.append("   - Match: task %d, method %d, setting %d" % (j["task"], j["method"], j["setting"]))
        codemap.append({"facet": f["id"], "facet_name": f["name"], "role": j.get("role", "match"),
                        "files": sorted(j.get("code") or {x["file"] for x in f.get("anchors", [])}),
                        "anchors": ["%s:%d" % (x["file"], x["line"]) for x in f.get("anchors", [])
                                    if not j.get("code") or x["file"] in j["code"]],
                        "cid": j["cid"], "title": p["title"], "year": p.get("year"), "url": p["url"], "doi": p.get("doi"),
                        "arxiv": p.get("arxiv"), "verified": status == "verified", "quote": j["quote"],
                        "reason": j["reason"]})
        if status == "verified":
            k = bib_key(p, used)
            fields = ["  title = {%s}" % bib_escape(p["title"]),
                      "  author = {%s}" % " and ".join(bib_escape(x) for x in p["authors"]),
                      "  year = {%s}" % (p.get("year") or "")]
            if p.get("venue"):
                fields.append("  journal = {%s}" % bib_escape(p["venue"]))
            if p.get("doi"):
                fields.append("  doi = {%s}" % p["doi"])
            if p.get("arxiv"):
                fields += ["  eprint = {%s}" % p["arxiv"], "  archivePrefix = {arXiv}"]
            fields.append("  url = {%s}" % p["url"])
            bib.append("@article{%s,\n%s\n}" % (k, ",\n".join(fields)))

    for f in profile["facets"]:
        rows = []
        for j in accepted:
            if j["facet"] != f["id"]:
                continue
            status, by = results[j["cid"]]
            if status in ("mismatch", "not_found"):
                dropped.append("%s (%s %s)" % (cands[j["cid"]]["title"], by, status))
            else:
                rows.append(j)
        rows.sort(key=lambda j: -(j["task"] + j["method"] + j["setting"]))
        lines += ["## %s: %s" % (f["id"], f["name"]), "",
                  "Project evidence: %s" % ", ".join("`%s`" % e for e in f["evidence"]), ""]
        matches = [j for j in rows if j.get("role", "match") == "match"]
        found = [j for j in rows if j.get("role") == "foundation"]
        for n, j in enumerate(matches, 1):
            render(j, n, f)
        if not matches:
            lines.append("No paper passed the relevance check for this facet. That is a valid result: "
                         "it means no strong match was found, not that the search failed.")
        if found:
            lines += ["", "Foundations (the original papers behind a method or library this code uses):", ""]
            for n, j in enumerate(found, 1):
                render(j, n, f)
        lines.append("")
    edges = [(c, r) for c, rs in cites.items() for r in rs]
    if edges:
        lines += ["## Lineage", "", "Listed papers that cite other listed papers (from OpenAlex references), "
                  "older work first. Read a foundation before the papers built on it.", ""]
        title = {c: "%s (%s)" % (cands[c]["title"], cands[c].get("year") or "n.d.") for c in cands}
        for r in sorted({r for _, r in edges}, key=lambda c: cands[c].get("year") or 0):
            users = sorted({c for c, x in edges if x == r}, key=lambda c: cands[c].get("year") or 0)
            lines.append("- %s is cited by: %s" % (title[r], "; ".join(title[c] for c in users)))
        lines.append("")
    for c in codemap:
        c["cites"] = [cands[r]["title"] for r in cites.get(c["cid"], [])]
    if codemap:
        by_file = {}
        for c in codemap:
            for fl in c["files"]:
                by_file.setdefault(fl, []).append(c)
        lines += ["## Code map", "", "Which papers explain which files. An agent can run "
                  "`papers.py lookup <file>` before changing that file.", ""]
        for fl in sorted(by_file):
            titles = sorted({"%s (%s)" % (c["title"], c["year"] or "n.d.") for c in by_file[fl]})
            lines.append("- `%s`: %s" % (fl, "; ".join(titles[:6]) + (" and %d more" % (len(titles) - 6)
                                                                      if len(titles) > 6 else "")))
        lines.append("")
    if dropped:
        lines += ["## Removed by verification", ""] + ["- %s" % d for d in dropped] + [""]
    os.makedirs(os.path.dirname(out_md) or ".", exist_ok=True)
    with open(out_md, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    with open(out_bib, "w", encoding="utf-8") as fh:
        fh.write("%% %s %s on %s.\n\n" % (GENERATED_MARK, VERSION, today) + "\n\n".join(bib) + ("\n" if bib else ""))
    out_json = os.path.splitext(out_md)[0] + ".json"
    with open(out_json, "w", encoding="utf-8") as fh:
        json.dump({"generated_by": "%s %s" % (GENERATED_MARK, VERSION), "date": today, "papers": codemap},
                  fh, ensure_ascii=False, indent=1)
    save_json(state_path(a.project, "codemap.json"), {"papers": codemap})
    state["accepted"] = sorted(set(state["accepted"]) | set(new_keys))
    save_json(state_path(a.project, "state.json"), state)
    counts = {}
    for s, _ in results.values():
        counts[s] = counts.get(s, 0) + 1
    print("wrote %s, %s and %s" % (out_md, out_bib, out_json))
    print(http.usage())
    print("papers listed: %d; verification: %s" % (len(accepted) - len(dropped), counts))
    for d in dropped:
        print("DROPPED " + d)


def cmd_lookup(a):
    """Papers that explain a file (or directory) of this project, for an agent about to change it."""
    data = load_json(state_path(a.project, "codemap.json"), "codemap.json (run finalize first)")
    target = os.path.normpath(os.path.relpath(os.path.abspath(a.path), a.project)
                              if os.path.isabs(a.path) or os.path.exists(a.path) else a.path)
    hits = [c for c in data["papers"] if any(fl == target or fl.startswith(target.rstrip(os.sep) + os.sep)
                                               for fl in c["files"])]
    if not hits:
        print("no paper is linked to %s" % target)
        return
    for c in hits:
        print("%s [%s, %s] %s (%s)%s" % (c["facet"], c["facet_name"], c["role"], c["title"], c["year"] or "n.d.",
                                         "" if c["verified"] else " NOT verified"))
        print("   %s" % c["url"])
        print('   abstract: "%s"' % c["quote"])
        print("   why: %s" % c["reason"])
        print("   code: %s" % ", ".join(c["anchors"]))
    print("Only the quoted sentence is checked. Anything else you recall about these papers (parameters, "
          "procedures, results) is unchecked: say so when you rely on it.")


def cmd_reject(a):
    cands = {p["cid"]: p for p in load_json(state_path(a.project, "candidates.json"), "candidates")["candidates"]}
    state = load_state(a.project)
    # C-ids refer to the most recent `search`.
    for cid in a.cids:
        p = cands.get(cid)
        if not p:
            print("unknown %s" % cid)
            continue
        state["rejected"] = sorted(set(state["rejected"]) | set(paper_keys(p)))
        print("rejected %s %s" % (cid, p["title"]))
    save_json(state_path(a.project, "state.json"), state)


