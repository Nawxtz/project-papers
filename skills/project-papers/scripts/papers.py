def resolve_evidence(project, scan, item):
    """Return (ok, label, is_doc, message)."""
    by_id = {e["id"]: e for e in scan["evidence"]}
    if isinstance(item, str):
        e = by_id.get(item)
        if not e:
            return False, item, False, "unknown evidence id %s" % item
        loc = "%s:%d" % (e["file"], e["line"]) if e["line"] else e["file"]
        return True, "%s (%s)" % (loc, e["value"]), False, ""
    if not isinstance(item, dict) or not {"file", "line", "quote"} <= set(item):
        return False, str(item), False, "evidence must be an E-id or {file,line,quote}"
    rel = os.path.normpath(str(item["file"]))
    if rel.startswith("..") or os.path.isabs(rel):
        return False, rel, False, "file must be inside the project"
    lines = read_lines(os.path.join(project, rel))
    if lines is None:
        return False, rel, False, "cannot read %s" % rel
    try:
        ln = int(item["line"])
    except (TypeError, ValueError):
        return False, rel, False, "line must be an integer"
    if not 1 <= ln <= len(lines):
        return False, rel, False, "%s has %d lines" % (rel, len(lines))
    q = norm_text(item["quote"])
    if len(q) < 4 or q not in norm_text(lines[ln - 1]):
        return False, "%s:%d" % (rel, ln), False, "quote not on %s:%d (line is: %r)" % (
            rel, ln, lines[ln - 1].strip()[:120])
    is_doc = os.path.splitext(rel)[1].lower() in DOC_EXT
    return True, "%s:%d" % (rel, ln), is_doc, ""


def str_list(v):
    return [x.strip() for x in v if isinstance(x, str) and x.strip()] if isinstance(v, list) else []


def check_profile(project, profile, scan):
    errors, warnings, facets = [], [], []
    if not isinstance(profile, dict):
        return ["profile must be a JSON object with a \"facets\" list"], [], {}
    raw = profile.get("facets")
    if raw == []:
        skips = coverage_check(scan, [], profile.get("skip"), errors)
        return errors, warnings, {"facets": [], "skip": skips}
    if not isinstance(raw, list) or not 1 <= len(raw) <= 6:
        errors.append("profile needs 1-6 facets")
        raw = raw if isinstance(raw, list) else []
    ids = set()
    known = {e["value"] for e in scan["evidence"] if e["kind"] == "paper_id"}
    by_id = {e["id"]: e for e in scan["evidence"]}
    for f in raw:
        if not isinstance(f, dict):
            errors.append("each facet must be a JSON object")
            continue
        fid = str(f.get("id", "")).strip()
        if not re.fullmatch(r"F\d+", fid) or fid in ids:
            errors.append("facet id must be unique F<number>: %r" % fid)
            continue
        ids.add(fid)
        for key in ("name", "task", "method"):
            if not str(f.get(key, "")).strip():
                errors.append("%s: missing %s" % (fid, key))
        queries = str_list(f.get("queries"))
        if not 1 <= len(queries) <= 4:
            errors.append("%s: needs 1-4 queries" % fid)
        labels, code_ev, anchors = [], 0, []
        for item in f.get("evidence") if isinstance(f.get("evidence"), list) else []:
            ok, label, is_doc, msg = resolve_evidence(project, scan, item)
            if not ok:
                errors.append("%s: %s" % (fid, msg))
            else:
                labels.append(label)
                code_ev += 0 if is_doc else 1
                e = by_id.get(item) if isinstance(item, str) else None
                anchors.append({"file": e["file"] if e else os.path.normpath(str(item["file"])),
                                "line": e["line"] if e else int(item["line"]), "id": item if e else None})
        if not labels:
            errors.append("%s: needs at least one valid evidence item" % fid)
        elif code_ev == 0:
            warnings.append("%s: only documentation evidence; confirm the code really does this" % fid)
        cites = []
        for c in f.get("seed_cites") if isinstance(f.get("seed_cites"), list) else []:
            ok, msg = check_cite(c, by_id)
            if ok:
                cites.append({"evidence": c["evidence"], "author": c["author"].strip(), "year": int(c["year"]),
                              "words": c["words"].strip()})
            else:
                errors.append("%s: seed_cites %s" % (fid, msg))
        seeds = str_list(f.get("seed_titles"))
        seed_ids = []
        for sid in str_list(f.get("seed_ids")):
            if sid not in known:
                errors.append("%s: seed id %s was not found in the project scan" % (fid, sid))
            else:
                seed_ids.append(sid)
        facets.append({"id": fid, "name": str(f.get("name", "")).strip(), "task": str(f.get("task", "")).strip(),
                       "method": str(f.get("method", "")).strip(), "setting": str(f.get("setting", "")).strip(),
                       "queries": queries, "seed_titles": seeds[:3], "seed_ids": seed_ids[:3], "evidence": labels,
                       "seed_cites": cites[:3], "anchors": anchors})
    if "seed_ids" in profile:
        errors.append("put seed_ids inside the facet they belong to, not at the top level")
    skips = coverage_check(scan, facets, profile.get("skip"), errors)
    return errors, warnings, {"facets": facets, "skip": skips}


def check_cite(c, by_id):
    """A seed citation must come from a citation found in the code: the author and year must
    appear in that evidence line, so the agent cannot cite from memory."""
    if not isinstance(c, dict) or not {"evidence", "author", "year", "words"} <= set(c):
        return False, "needs evidence, author, year and words"
    e = by_id.get(str(c["evidence"]))
    if not e or e["kind"] not in ("citation", "doc"):
        return False, "evidence %s is not a citation or doc line from the scan" % c.get("evidence")
    text = norm_text(e["text"] + " " + e["value"])
    try:
        year = int(c["year"])
    except (TypeError, ValueError):
        return False, "year must be a number"
    if norm_text(str(c["author"])) not in text or str(year) not in text:
        return False, "author %r and year %s must both appear in %s" % (c["author"], year, e["id"])
    words = content_terms(str(c["words"]))
    if len(words) < 2:
        return False, "words needs at least 2 title words, for example \"Deflated Sharpe Ratio\""
    missing = words - content_terms(e["text"])
    if missing:
        return False, "words must be copied from line %s:%d; not there: %s" % (e["file"], e["line"], ", ".join(sorted(missing)))
    return True, ""


def coverage_check(scan, facets, raw_skips, errors):
    """Every top technique from the scan must be covered by a facet (same evidence id, or any
    evidence in the same file) or skipped with a reason. This makes different agents look at
    the same parts of the code instead of whatever they happened to open."""
    by_id = {e["id"]: e for e in scan["evidence"]}
    anchors = [a for f in facets for a in f.get("anchors", [])]
    used = {a["id"] for a in anchors if a.get("id")}
    items_in_file = {}
    for eid in scan.get("coverage", []):
        if eid in by_id:
            items_in_file[by_id[eid]["file"]] = items_in_file.get(by_id[eid]["file"], 0) + 1

    def near(e):
        # Any anchor in the file covers a file's only item; with several items in one file
        # (a notebook), each needs an anchor within 40 lines.
        same = [a for a in anchors if a["file"] == e["file"]]
        if items_in_file.get(e["file"], 0) <= 1:
            return bool(same)
        return any(abs(a["line"] - ln) <= 40 for a in same for ln in e.get("sites") or [e["line"]])
    skips = {}
    for sk in raw_skips if isinstance(raw_skips, list) else []:
        if isinstance(sk, dict) and str(sk.get("evidence")) in by_id:
            reason = str(sk.get("reason", "")).strip()
            if len(reason) < 10:
                errors.append("skip %s: give a reason of 10+ characters" % sk.get("evidence"))
            else:
                skips[str(sk["evidence"])] = reason[:200]
        else:
            errors.append("skip entries must be {\"evidence\": \"E<n>\", \"reason\": \"...\"} with a scan id")
    for eid in scan.get("coverage", []):
        e = by_id.get(eid)
        if not e or eid in used or near(e) or eid in skips:
            continue
        errors.append("not covered: %s %s [%s:%d]. Add a facet that cites it or this file, or add "
                      "{\"evidence\": \"%s\", \"reason\": \"...\"} to \"skip\"" % (eid, e["value"], e["file"], e["line"], eid))
    return [{"evidence": k, "reason": v} for k, v in skips.items()]


