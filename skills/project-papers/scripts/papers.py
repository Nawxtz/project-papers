            comment, first_doc = None, False
            st = ln.strip()
            if ext == ".py":
                quotes = st.count('"""') + st.count("'''")
                if in_doc:
                    comment = st.strip('"\' ')
                    if quotes % 2:
                        in_doc = False
                elif quotes:
                    m = re.match(r"[rRbBuU]?(\"\"\"|\'\'\')(.*?)(?:\1|$)", st)
                    if m:
                        comment = m.group(2).strip()
                        first_doc = doc_first or i <= 3 or bool(re.match(r"\s*(def|class)\s", lines[i - 2] if i > 1 else ""))
                        in_doc = quotes % 2 == 1
