def main(argv=None):
    ap = argparse.ArgumentParser(prog="papers.py", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", default=".", help="project root (default: current directory)")
    ap.add_argument("--offline", action="store_true", help="use cached responses only")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("scan")
    p.add_argument("--limit", type=int, default=40, help="max items printed per kind")
    p = sub.add_parser("check")
