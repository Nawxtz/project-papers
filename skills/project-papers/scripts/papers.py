#!/usr/bin/env python3
"""project-papers: find research papers that match what a code project actually does.

Stdlib only. The agent never writes paper metadata: this script fetches it,
checks every claim the agent makes against fetched text, and renders the output.

Commands (run from anywhere, pass the project root with --project, default "."):
  scan       collect evidence from the project (deps, imports, model refs, paper IDs)
  check      validate profile.json (facets must cite evidence) and print the review table
  search     query OpenAlex + Crossref per facet, expand from seed papers, dedupe, score
  show       print a compact candidate list for the agent to judge
  judge      validate judgments.json (IDs, verbatim quotes, rubric threshold)
  finalize   verify accepted papers against Crossref/arXiv, write papers.md + papers.bib
  reject     never show these candidates again (by C-id)
  lookup     papers linked to a file or directory (for an agent about to change that code)

State lives in <project>/.papers/ (add it to .gitignore if you do not want it committed).
"""
