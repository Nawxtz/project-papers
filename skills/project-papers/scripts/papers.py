def iter_files(project):
    count = 0
    seen_dirs = set()
    # followlinks: monorepos often link a sub-project in; seen_dirs stops symlink loops.
    for root, dirs, files in os.walk(project, followlinks=True):
        real = os.path.realpath(root)
        if real in seen_dirs:
            dirs[:] = []
            continue
        seen_dirs.add(real)
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith("."))
        for name in sorted(files):
            path = os.path.join(root, name)
            rel = os.path.relpath(path, project)
            ext = os.path.splitext(name)[1].lower()
            yield rel, path, ext
            count += 1
            if count >= MAX_FILES:
                return


def read_lines(path):
    try:
        limit = MAX_NOTEBOOK_BYTES if path.endswith(".ipynb") else MAX_FILE_BYTES
        if os.path.getsize(path) > limit:
            return None
        with open(path, encoding="utf-8", errors="strict") as f:
            return f.read().splitlines()
    except (UnicodeDecodeError, OSError):
        return None


def js_package(spec):
    """Package name of an import spec, or None for aliases, relative paths and Node built-ins."""
    if spec.startswith(("@/", "~/", "#", "node:", "http:", "https:", "/")) or "${" in spec:
        return None
    parts = spec.split("/")
    name = "/".join(parts[:2]) if spec.startswith("@") and len(parts) > 1 else parts[0]
    return None if name in NODE_BUILTINS else name


def dep_lines(base, ext, lines):
    """Yield (line_no, package) for dependency manifests other than requirements/pyproject/package.json."""
    section = ""
    section_pom = [False]
    for i, ln in enumerate(lines, 1):
        s = ln.split("#")[0].rstrip() if base not in ("pom.xml",) else ln
        hdr = re.match(r"\s*\[([^\]]+)\]", s)
        if hdr:
            section = hdr.group(1).strip().lower()
            continue
        if base == "go.mod":
            m = re.match(r"\s*(?:require\s+)?([\w.-]+\.[a-z]{2,}/[\w./-]+)\s+v\d", s)
        elif base == "cargo.toml" or (base == "pyproject.toml" and "poetry" in section):
            ok = section.endswith("dependencies") or section.endswith("dev-dependencies")
            m = re.match(r"\s*([A-Za-z0-9][\w.-]*)\s*=", s) if ok else None
            if m and m.group(1).lower() == "python":
                m = None
        elif base in ("environment.yml", "environment.yaml"):
            m = re.match(r"\s*-\s+([A-Za-z0-9][\w.-]*)\s*(?:[=<>!~].*)?$", s)
            if m and m.group(1).lower() in ("pip", "python"):
                m = None
        elif base == "pom.xml":
            m = re.search(r"<artifactId>([\w.-]+)</artifactId>", s) if section_pom[0] else None
            if "<dependency>" in s:
                section_pom[0] = True
            if "</dependency>" in s:
                section_pom[0] = False
        elif base in ("build.gradle", "build.gradle.kts"):
            m = re.search(r"""(?:implementation|api|compile)\s*\(?\s*['"]([\w.-]+:[\w.-]+)""", s)
        elif base == "gemfile":
            m = re.match(r"""\s*gem\s+['"]([\w.-]+)['"]""", s)
        else:
            return
        if m:
            yield i, m.group(1)


