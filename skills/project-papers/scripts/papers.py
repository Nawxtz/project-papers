def load_keys_file():
    """Fill missing env vars from $XDG_CONFIG_HOME/project-papers/keys.env (KEY=VALUE lines)."""
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.join(os.path.expanduser("~"), ".config")
    path = os.path.join(base, "project-papers", "keys.env")
    if not os.path.isfile(path):
        return
    with open(path, encoding="utf-8") as f:
        for ln in f:
            key, sep, val = ln.strip().partition("=")
            if sep and key in ("OPENALEX_API_KEY", "PAPERS_MAILTO") and val.strip():
                os.environ.setdefault(key, val.strip().strip("'\""))


