def oa_to_paper(w):
    doi = (w.get("doi") or "").replace("https://doi.org/", "").lower() or None
    arxiv = None
    if doi and doi.startswith("10.48550/arxiv."):
        arxiv, doi = doi.split("arxiv.", 1)[1], None
    loc = w.get("primary_location") or {}
    land = loc.get("landing_page_url") or ""
    m = re.search(r"arxiv\.org/abs/(\d{4}\.\d{4,5})", land)
    if m and not arxiv:
        arxiv = m.group(1)
    src = loc.get("source") or {}
    authors = [(x.get("author") or {}).get("display_name") for x in (w.get("authorships") or [])]
    authors = [x for x in authors if x]
    abstract = clean_text(rebuild_abstract(w.get("abstract_inverted_index")))
    if looks_like_byline(abstract, authors):
        abstract = ""  # some records hold the author list instead of an abstract; nothing to quote
    return {
        "title": clean_text(w.get("title") or w.get("display_name")),
        "type": w.get("type") or "",
        "year": w.get("publication_year"),
        "authors": authors,
        "venue": src.get("display_name") or "",
        "venue_class": venue_class(w.get("type"), src, arxiv),
        "source_id": (src.get("id") or "").rsplit("/", 1)[-1],
        "cited_by": w.get("cited_by_count") or 0,
        "doi": doi, "arxiv": arxiv, "openalex": (w.get("id") or "").rsplit("/", 1)[-1],
        "url": ("https://doi.org/" + doi) if doi else ("https://arxiv.org/abs/" + arxiv if arxiv else land or w.get("id")),
        "abstract": abstract,
        "related": [r.rsplit("/", 1)[-1] for r in (w.get("related_works") or [])],
    }


VENUE_H_INDEX = 80


def venue_class(work_type, src, arxiv=None, h_index=None):
    """established: OpenAlex lists the source as core (CWTS) or its h-index is >= 80. The core
    list misses big CS conferences (KDD h=329, AAAI 309, IJCAI 202), hence the h-index rule;
    outlets of short student write-ups seen in testing sat at 24-65.
    preprint/thesis/book: judged on content. unvetted: any other journal or conference."""
    if src.get("is_core") or (h_index or 0) >= VENUE_H_INDEX:
        return "established"
    if (work_type or "") == "dissertation":
        return "thesis"
    if arxiv or (work_type or "") == "preprint" or src.get("type") == "repository":
        return "preprint"
    if src.get("type") in ("ebook platform", "book series") or (work_type or "") in ("book", "book-chapter"):
        return "book"
    return "unvetted" if src else "unknown"


def looks_like_byline(text, authors):
    head = norm_text(text[:300])
    named = sum(1 for a in authors[:6] if a and norm_text(a) in head)
    return bool(text) and named >= min(2, len(authors)) and named > 0


def or_query(f):
    return " OR ".join("(%s)" % q for q in f["queries"])


def crossref_to_paper(it):
    ab = re.sub(r"^\s*(abstract|summary)\b[:.]?", "", clean_text(it.get("abstract")), flags=re.I).strip()
    doi = (it.get("DOI") or "").lower() or None
    authors = [" ".join(x for x in (a.get("given"), a.get("family")) if x) for a in it.get("author") or []]
    return {
        "title": clean_text((it.get("title") or [""])[0]),
        "type": it.get("type") or "",
        "year": ((it.get("issued") or {}).get("date-parts") or [[None]])[0][0],
        "authors": [x for x in authors if x],
        "venue": (it.get("container-title") or [""])[0],
        "venue_class": "unknown",  # filled from OpenAlex after the search
        "cited_by": it.get("is-referenced-by-count") or 0,
        "doi": doi, "arxiv": None, "openalex": None,
        "url": "https://doi.org/" + doi if doi else "",
        "abstract": ab, "related": [],
    }


OA_SELECT = ("id,doi,title,display_name,publication_year,cited_by_count,authorships,"
             "primary_location,abstract_inverted_index,related_works,type")


def parse_arxiv(xml_text):
    ns = {"a": "http://www.w3.org/2005/Atom", "x": "http://arxiv.org/schemas/atom"}
    out = []
    root = ET.fromstring(xml_text)
    for e in root.findall("a:entry", ns):
        aid = (e.findtext("a:id", "", ns) or "").rsplit("/abs/", 1)[-1]
        aid = re.sub(r"v\d+$", "", aid)
        if not re.fullmatch(r"\d{4}\.\d{4,5}", aid):
            continue
        doi = (e.findtext("x:doi", "", ns) or "").lower() or None
        out.append({
            "title": re.sub(r"\s+", " ", e.findtext("a:title", "", ns)).strip(),
            "year": int((e.findtext("a:published", "", ns) or "0")[:4] or 0) or None,
            "authors": [a.findtext("a:name", "", ns) for a in e.findall("a:author", ns)],
            "venue": "arXiv", "venue_class": "preprint", "cited_by": 0, "doi": doi, "arxiv": aid, "openalex": None,
            "url": "https://arxiv.org/abs/" + aid,
            "abstract": re.sub(r"\s+", " ", e.findtext("a:summary", "", ns)).strip(),
            "related": [],
        })
    return out


def paper_keys(p):
    keys = []
    if p.get("doi"):
        keys.append("doi:" + p["doi"])
    if p.get("arxiv"):
        keys.append("arxiv:" + p["arxiv"])
    t = norm_title(p.get("title"))
    if t:
        keys.append("title:" + t)
    return keys


class Pool:
    """Merges papers from all sources; dedupes on DOI, arXiv ID or normalized title."""

    def __init__(self, rejected):
        self.items = []
        self.index = {}
        self.rejected = set(rejected)
        self.lock = threading.Lock()

    def add(self, p, facet, source, seed=False, graph=False, method=None, rank=0):
        keys = paper_keys(p)
        if not keys or not p.get("title") or self.rejected.intersection(keys) or not_a_paper(p):
            return
        with self.lock:
            hit = next((self.index[k] for k in keys if k in self.index), None)
            if hit is None:
                hit = dict(p, facets=[], sources=[], hits=0, seed=False, graph=False)
                self.items.append(hit)
            else:
                for f in ("doi", "arxiv", "openalex", "venue"):
                    if not hit.get(f) and p.get(f):
                        hit[f] = p[f]
                if hit.get("venue_class", "unknown") == "unknown" and p.get("venue_class"):
                    hit["venue_class"] = p["venue_class"]
                if len(p.get("abstract") or "") > len(hit.get("abstract") or ""):
                    hit["abstract"] = p["abstract"]
                hit["cited_by"] = max(hit["cited_by"] or 0, p.get("cited_by") or 0)
                if p.get("doi") and hit["url"].startswith("https://openalex"):
                    hit["url"] = "https://doi.org/" + p["doi"]
            for k in paper_keys(hit):
                self.index[k] = hit
            if facet not in hit["facets"]:
                hit["facets"].append(facet)
            if method:
                key = "%s/%s" % (facet, method)
                origins = hit.setdefault("origins", {})
                origins[key] = min(origins.get(key, rank), rank)
            if source not in hit["sources"]:
                hit["sources"].append(source)
            hit["hits"] += 1
            hit["seed"] = hit["seed"] or seed
            hit["graph"] = hit["graph"] or graph


NOT_PAPER_TYPES = {"erratum", "paratext", "retraction", "peer-review", "component", "grant", "letter"}
RE_NOT_PAPER_TITLE = re.compile(r"^\s*(correction|erratum|corrigendum|retraction|retracted|withdrawn|"
                                r"reply to|response to|comment on|author correction)\b", re.I)


def not_a_paper(p):
    """Corrections, retractions and editorial notices repeat another paper's title or abstract."""
    return (p.get("type") or "").lower() in NOT_PAPER_TYPES or bool(RE_NOT_PAPER_TITLE.match(p.get("title") or ""))


def score(p, this_year):
    s = 3.0 * p["seed"] + 2.0 * p["graph"] + 1.5 * len(p["facets"]) + min(p["hits"], 5)
    s += 0.6 * math.log10((p["cited_by"] or 0) + 1)
    if p.get("year") and p["year"] >= this_year - 5:
        s += 0.5
    return round(s, 2)


# From testing: "gradient boosting" matched 104,014 papers and pulled in house prices and goat
# genomics; useful queries matched 200-500. Niche topics legitimately match under 10
# ("triple barrier labeling machine learning trading": 8, all on topic), so only 0 is flagged.
QUERY_TOO_BROAD = 20000


def cmd_search(a):
    profile = load_json(state_path(a.project, "profile.json"), "checked profile (run check first)")
    state = load_state(a.project)
    http = Http(a.project, offline=a.offline)
    pool = Pool(state["rejected"])
    warnings = []
    oa_ok = []
    seeds_by_facet = {}

    query_counts = {}
    facet_counts = {}  # papers matching the facet's OR query, free with the text search

    def oa_count(fid, q):
        try:
            data = http.openalex("works", {"filter": "title_and_abstract.search:" + q.replace(",", " "),
                                           "per_page": 1, "select": "id"})
            query_counts[(fid, q)] = (data.get("meta") or {}).get("count")
        except Exception:
            pass  # only a quality hint; the search itself does not depend on it

    def oa_search(fid, q):
        # Benchmark (bench/): title+abstract filter beat the `search=` param and arXiv on precision.
        params = {"filter": "title_and_abstract.search:" + q.replace(",", " "),
                  "per_page": a.per_query, "select": OA_SELECT}
        try:
            data = http.openalex("works", params)
        except Exception as e:  # keep going; report at the end
            warnings.append("OpenAlex query failed (%s): %s" % (q, e))
            return
        oa_ok.append(q)
        facet_counts[fid] = (data.get("meta") or {}).get("count") or 0
        for r, w in enumerate(data.get("results", [])):
            pool.add(oa_to_paper(w), fid, "openalex", method="text", rank=r)

    def oa_citing(fid, seed_id, q):
        # Papers citing the seed, ranked by relevance to the facet queries.
        try:
            data = http.openalex("works", {"filter": "cites:" + seed_id, "search": q,
                                           "per_page": a.per_query, "select": OA_SELECT})
        except Exception as e:
            warnings.append("citing-papers lookup failed (%s): %s" % (seed_id, e))
            return
        for r, w in enumerate(data.get("results", [])):
            pool.add(oa_to_paper(w), fid, "openalex", graph=True, method="citing", rank=r)

    def crossref_search(fid, q):
        url = "https://api.crossref.org/works?" + urllib.parse.urlencode(
            {"query.bibliographic": q, "rows": a.per_query, "filter": "has-abstract:true",
             "select": "DOI,title,abstract,author,issued,is-referenced-by-count,container-title,type"})
        try:
            items = http.get_json(url)["message"]["items"]
        except Exception as e:
            warnings.append("Crossref query failed (%s): %s" % (q, e))
            return
        for r, it in enumerate(items):
            p = crossref_to_paper(it)
            if p["abstract"]:
                pool.add(p, fid, "crossref", method="crossref", rank=r)

    def arxiv_search(fid, q):
        terms = [t for t in re.findall(r"[A-Za-z0-9\-]+", q) if len(t) > 2]
        if not terms:
            return
        sq = " AND ".join("all:%s" % t for t in terms[:6])
        url = "https://export.arxiv.org/api/query?" + urllib.parse.urlencode(
            {"search_query": sq, "max_results": a.per_query, "sortBy": "relevance"})
        try:
            for r, p in enumerate(parse_arxiv(http.get(url, arxiv=True, kind="arxiv"))):
                pool.add(p, fid, "arxiv", method="arxiv", rank=r)
        except Exception as e:
            warnings.append("arXiv query failed (%s): %s" % (q, e))

    def resolve_title(fid, title):
        best, matched = None, False
        try:
            # ":" and "," are filter syntax in OpenAlex; a colon in the value returns nothing.
            data = http.openalex("works", {"filter": "title.search:" + re.sub(r"[,:;|!]", " ", title),
                                           "per_page": 5, "select": OA_SELECT, "sort": "cited_by_count:desc"})
            best = max(data.get("results", []), key=lambda w: title_sim(w.get("title"), title), default=None)
            matched = bool(best) and title_sim(best.get("title"), title) >= 0.9
        except Exception as e:
            warnings.append("OpenAlex seed search failed, trying Crossref (%s): %s" % (title, e))
        if not matched:
            # Fallback: find the DOI on Crossref, then fetch the record by DOI (not a search call).
            # Crossref keeps the subtitle apart ("XGBoost" + "A Scalable Tree Boosting System"), so
            # compare the joined title too.
            try:
                url = "https://api.crossref.org/works?" + urllib.parse.urlencode(
                    {"query.bibliographic": title, "rows": 5, "select": "DOI,title,subtitle"})
                items = http.get_json(url)["message"]["items"]

                def sim(it):
                    main = (it.get("title") or [""])[0]
                    sub = (it.get("subtitle") or [""])[0]
                    return max(title_sim(main, title), title_sim("%s: %s" % (main, sub), title) if sub else 0)
                hit = max(items, key=sim, default=None)
                if hit and sim(hit) >= 0.9:
                    best = http.openalex("works/doi:" + hit["DOI"].lower(), {"select": OA_SELECT})
                    matched = True
            except Exception as e:
                warnings.append("Crossref seed lookup failed (%s): %s" % (title, e))
        if matched and best:
            p = oa_to_paper(best)  # keep the registry's title, even when it drops the subtitle
            pool.add(p, fid, "openalex", seed=True, method="seed")
            seeds_by_facet.setdefault(fid, []).append(p)
        else:
            warnings.append("seed not found, skipped (not guessed): %s" % title)

    def resolve_cite(fid, c):
        # A citation found in the code ("Bailey & Lopez de Prado (2014) Deflated Sharpe Ratio"):
        # first author's surname + year +-1 + title words. Only an unambiguous hit becomes a seed.
        surname = re.split(r"\s+(?:&|and|et)\s+", c["author"])[0].split()[-1]
        try:
            data = http.openalex("works", {
                "filter": "raw_author_name.search:%s,publication_year:%d-%d,title.search:%s" % (
                    re.sub(r"[,:|]", " ", surname), c["year"] - 1, c["year"] + 1, re.sub(r"[,:;|!]", " ", c["words"])),
                "per_page": 5, "select": OA_SELECT, "sort": "cited_by_count:desc"})
        except Exception as e:
            warnings.append("citation lookup failed (%s %s): %s" % (c["author"], c["year"], e))
            return
        words = content_terms(c["words"])
        hits = [w for w in data.get("results", [])
                if len(stem_overlap(words, content_terms(w.get("title")))) >= max(2, len(words) - 1)]
        if not hits:
            warnings.append("citation not found, skipped (not guessed): %s %s %s" % (c["author"], c["year"], c["words"]))
            return
        p = oa_to_paper(hits[0])
        pool.add(p, fid, "openalex", seed=True, method="seed")
        seeds_by_facet.setdefault(fid, []).append(p)

    def resolve_id(fid, sid):
        if sid.startswith("arXiv:"):
            path = "works/doi:10.48550/arxiv." + sid[6:]
        else:
            path = "works/doi:" + sid[4:]
        try:
            w = http.openalex(path, {"select": OA_SELECT})
        except Exception as e:
            warnings.append("seed id lookup failed (%s): %s" % (sid, e))
            return
        p = oa_to_paper(w)
        pool.add(p, fid, "openalex", seed=True, method="seed")
        seeds_by_facet.setdefault(fid, []).append(p)

    t0 = time.time()

    def expand(f):
        """Graph expansion for one facet: papers that cite a seed AND match the facet topic,
        plus the seeds' related works."""
        jobs = []
        for seed in seeds_by_facet.get(f["id"], [])[:2]:
            if seed.get("openalex"):
                jobs.append(ex.submit(oa_citing, f["id"], seed["openalex"], or_query(f)))
        related = [r for s in seeds_by_facet.get(f["id"], []) for r in s.get("related", [])][:25]
        if related:
            def fetch_related(fid=f["id"], ids=related):
                try:
                    data = http.openalex("works", {"filter": "openalex_id:" + "|".join(ids),
                                                   "per_page": len(ids), "select": OA_SELECT})
                except Exception as e:
                    warnings.append("related works lookup failed: %s" % e)
                    return
                order = {i: n for n, i in enumerate(ids)}
                for w in data.get("results", []):
                    p = oa_to_paper(w)
                    pool.add(p, fid, "openalex", graph=True, method="related",
                             rank=order.get(p["openalex"], len(ids)))
            jobs.append(ex.submit(fetch_related))
        return jobs

    arxiv_thread = None
    if a.arxiv:
        def run_arxiv():
            for f in profile["facets"]:
                for q in f["queries"][:2]:
                    arxiv_search(f["id"], q)
        arxiv_thread = threading.Thread(target=run_arxiv)
        arxiv_thread.start()
    # One pool for everything. Crossref answers slowly (up to 5 s), so it runs alongside the
    # OpenAlex work instead of before it: graph expansion for a facet starts as soon as that
    # facet's seeds are resolved. OpenAlex calls stay paced by Http's lock.
    with ThreadPoolExecutor(max_workers=6) as ex:
        slow = [ex.submit(crossref_search, f["id"], " ".join(f["queries"])) for f in profile["facets"]]
        # One OpenAlex request per facet: queries joined with OR (saves the daily budget).
        text = [ex.submit(oa_search, f["id"], or_query(f)) for f in profile["facets"]]
        seed_jobs = {f["id"]: [ex.submit(resolve_title, f["id"], t) for t in f["seed_titles"]]
                     + [ex.submit(resolve_id, f["id"], s) for s in f.get("seed_ids", [])]
                     + [ex.submit(resolve_cite, f["id"], c) for c in f.get("seed_cites", [])]
                     for f in profile["facets"]}
        later = []
        for f in profile["facets"]:
            for j in seed_jobs[f["id"]]:
                j.result()
            later += expand(f)
        for j in text:
            j.result()
        # The OR query matches at least as many papers as any one of its queries, so a single
        # query can only be too broad when the facet total is. Count queries one by one only
        # then (in testing this saved 14 of 49 requests). A one-query facet's total is its count.
        for f in profile["facets"]:
            if len(f["queries"]) == 1 and f["id"] in facet_counts:
                query_counts[(f["id"], f["queries"][0])] = facet_counts[f["id"]]
        later += [ex.submit(oa_count, f["id"], q) for f in profile["facets"] for q in f["queries"]
                  if len(f["queries"]) > 1 and facet_counts.get(f["id"], 0) > QUERY_TOO_BROAD]
        for j in slow + later:
            j.result()
    if arxiv_thread:
        arxiv_thread.join()

    # Crossref has no venue-quality flag: look the DOIs up in OpenAlex, 50 per request.
    unknown = [p for p in pool.items if p.get("venue_class", "unknown") == "unknown" and p.get("doi")]
    for i in range(0, len(unknown), 50):
        chunk = {p["doi"]: p for p in unknown[i:i + 50]}
        try:
            data = http.openalex("works", {"filter": "doi:" + "|".join(chunk), "per_page": 50,
                                           "select": "doi,type,primary_location"})
        except Exception as e:
            warnings.append("venue lookup failed: %s" % e)
            break
        for w in data.get("results", []):
            p = chunk.get((w.get("doi") or "").replace("https://doi.org/", "").lower())
            if p:
                src = (w.get("primary_location") or {}).get("source") or {}
                p["venue_class"] = venue_class(w.get("type"), src)
                p["source_id"] = (src.get("id") or "").rsplit("/", 1)[-1]
    # Second pass for journals and conferences outside the core list: use the source h-index.
    pending = {}
    for p in pool.items:
        if p.get("venue_class") == "unvetted" and p.get("source_id"):
            pending.setdefault(p["source_id"], []).append(p)
    sids = list(pending)
    for i in range(0, len(sids), 50):
        try:
            data = http.openalex("sources", {"filter": "openalex_id:" + "|".join(sids[i:i + 50]), "per_page": 50,
                                             "select": "id,summary_stats"})
        except Exception as e:
            warnings.append("venue lookup failed: %s" % e)
            break
        for src in data.get("results", []):
            h = (src.get("summary_stats") or {}).get("h_index") or 0
            if h >= VENUE_H_INDEX:
                for p in pending.get(src["id"].rsplit("/", 1)[-1], []):
                    p["venue_class"] = "established"

    this_year = dt.date.today().year
    for p in pool.items:
        p["score"] = score(p, this_year)
        p.pop("related", None)
    pool.items.sort(key=lambda p: -p["score"])
    # C-ids are stable across searches: a paper seen before keeps its id, so judgments.json and
    # `reject` stay valid after a re-run. New papers get the next free number.
    ids = state.setdefault("ids", {})
    nxt = max([int(v[1:]) for v in ids.values()] + [0]) + 1
    for p in pool.items:
        keys = paper_keys(p)
        cid = next((ids[k] for k in keys if k in ids), None)
        if cid is None:
            cid, nxt = "C%d" % nxt, nxt + 1
        p["cid"] = cid
        for k in keys:
            ids[k] = cid
    save_json(state_path(a.project, "state.json"), state)
    no_abs = sum(1 for p in pool.items if not p["abstract"])
    save_json(state_path(a.project, "candidates.json"),
              {"created": dt.datetime.now().isoformat(timespec="seconds"), "warnings": warnings,
               "query_counts": ["%s\t%s\t%s" % (k[0], k[1], v) for k, v in query_counts.items()],
               "candidates": pool.items})
    print("found %d unique candidates in %.1fs (%d without abstract, cannot be accepted)"
          % (len(pool.items), time.time() - t0, no_abs))
    for f in profile["facets"]:
        n = sum(1 for p in pool.items if f["id"] in p["facets"])
        s = len(seeds_by_facet.get(f["id"], []))
        print("  %s %s: %d candidates, %d seed papers" % (f["id"], f["name"], n, s))
    print(http.usage())
    for f in profile["facets"]:
        for q in f["queries"]:
            n = query_counts.get((f["id"], q))
            if n is None:
                continue
            if n > QUERY_TOO_BROAD:
                print("WARN %s query matches %d papers, too broad (results drift off topic): %r. "
                      "Add the task or domain words, then run check and search again." % (f["id"], n, q))
            elif n == 0:
                print("WARN %s query matches no paper: %r. Drop a word or use the term papers use." % (f["id"], q))
    for w in warnings:
        print("WARN " + w)
    if not oa_ok:
        print("WARN OpenAlex text search failed; results come from fallbacks only (seed graph, Crossref). "
              "Recall is lower. A free OPENALEX_API_KEY avoids this.")
    if not any(p["abstract"] for p in pool.items):
        print("ERROR no candidate with an abstract was found; nothing can be judged. Treat this run as failed.")
        sys.exit(3)


